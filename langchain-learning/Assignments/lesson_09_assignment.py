# Create the embedding model
from langchain_google_genai import GoogleGenerativeAIEmbeddings

embeddings = GoogleGenerativeAIEmbeddings(
    model="models/gemini-embedding-001",
    google_api_key=API_KEY,
)

# Create the vector store
from langchain_core.vectorstores import InMemoryVectorStore

vector_store = InMemoryVectorStore(embedding = embeddings)

vector_store.add_documents(documents)

# Create the formatting function
def format_docs(documents: list[Document])->str:
    docs = "\n\n".join(
        f"Page content: {doc.page_content}\n Page_source: {doc.metadata}"
        for doc in documents
        )
    return docs

# Convert the format function to runnable
from langchain_core.runnables import RunnableLambda
format_docs_runnable = RunnableLambda(format_docs)


# Create the retriever
retriever = vector_store.as_retriever(
    search_kwargs = {
        "k": 3,
        "fetch_k":10,
    }
)

query = "What is LangGraph?"


# Create retriever chain
from langchain_core.runnables import RunnableParallel, RunnablePassthrough
retriever_chain = RunnableParallel({
    "context": retriever| format_docs_runnable ,
    "query":RunnablePassthrough()
})

# Create prompt
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
prompt = ChatPromptTemplate.from_messages(
    [
    ("system", "Answer the given query based only on the given context. If context does not provide the answer say I dont know"),
    ("human", "Question: {query}, \nContext: {context}"),
    ]
)

# RAG chain
from langchain_core.output_parsers import StrOutputParser
initial_rag_chain = retriever_chain | prompt | llm | StrOutputParser()|RunnableLambda (lambda x:str(x))

