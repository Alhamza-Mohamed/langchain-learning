# Create query rewriter prompt
from langchain_core.prompts import  MessagesPlaceholder
query_rewriter_prompt = ChatPromptTemplate.from_messages(
    [
    ("system", "You are going to receive a history and the current query. Your job is to rewrite the second query so it can be understood without the context of the history with no ambiguity. If the history is empty this mean the query is the initial query, you suppose to return it with not change"),
    MessagesPlaceholder("history"),
    ("human", "Question: {query}"),
    ]
)

# Create history prompt
history_prompt = ChatPromptTemplate.from_messages(
    [
    ("system", "Answer the given query based only on the given context. If context does not provide the answer say I dont know"),
    MessagesPlaceholder("history"),
    ("human", "Question: {query}, \nContext: {context}"),
    ]
)

# Create rewritten query chain
query_rewriting_chain = RunnableParallel({
    "rewritten_query" : query_rewriter_prompt | llm | StrOutputParser() | RunnableLambda (lambda x:str(x)) ,
    "query": RunnablePassthrough()
    })

# Create retriever chain
retriever_chain = RunnableParallel({
    "context":  query_rewriting_chain | RunnableLambda (lambda x:x["rewritten_query"]) | retriever | format_docs_runnable ,
    "history": RunnableLambda (lambda x:x["history"]) | RunnablePassthrough(),
    "query":RunnableLambda (lambda x:x["query"]) | RunnablePassthrough()
})

# Create the conversational RAG
conversational_rag_chain = retriever_chain | history_prompt | llm | StrOutputParser()


print(respond) # >> Based on the provided context, the difference is that LangGraph is designed for stateful agent workflows, whereas LangChain provides abstractions for building LLM applications.

